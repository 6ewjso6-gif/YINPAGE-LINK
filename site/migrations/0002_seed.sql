## 构建期把能算的都算完

Markdown 解析、代码高亮、目录生成、摘要提取，这些都不需要等到用户打开页面才做。它们可以在构建时完成，把结果直接写进 HTML。

```js
// 构建时执行一次，而不是每个访客执行一次
const html = marked.parse(markdown);
```

于是交付顺序变了：

1. HTML 先到，标题、正文、导航都在
2. CSS 到，页面成型
3. JavaScript 最后到，只负责搜索、筛选这类真正的交互

## 这不是“不要 JS”

账号、评论、搜索、编辑器仍然需要客户端。区别在于，它们不该拦在正文前面。

